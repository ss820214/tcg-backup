function normalizeCardId(cardId) {
  return String(cardId || "").trim().toLowerCase();
}

function assetUrl(fileName) {
  return `./assets/card_illustrations/${fileName}?v=${CARD_ILLUSTRATION_VERSION}`;
}

export function cardIllustrationEntry(cardId) {
  return CARD_ILLUSTRATIONS[normalizeCardId(cardId)] || null;
}

export function cardIllustrationSrc(cardId, variantIndex = 0) {
  const entry = cardIllustrationEntry(cardId);
  if (!entry) return "";
  const variants = Array.isArray(entry.variants) ? entry.variants.filter(Boolean) : [];
  const selected = variants.length
    ? variants[Math.max(0, Number(variantIndex) || 0) % variants.length]
    : entry.default;
  return selected ? assetUrl(selected) : "";
}
