import assert from 'node:assert/strict';
import {buildHandGuidance as guide} from '../public/hand_guidance.js';
const base={hasCard:true,canAct:true,mode:'summon',mana:4,cost:2,summonSpace:true,evolveCandidates:true};
assert.match(guide(base).text,/空きマス.*召喚/);
assert.equal(guide(base).modeDisabled,false);
assert.equal(guide({...base,hasCard:false}).boardVisible,false);
assert.match(guide({...base,canAct:false}).text,/相手のターン/);
assert.equal(guide({...base,canAct:false}).modeDisabled,true);
assert.match(guide({...base,winner:true}).text,/対戦終了/);
assert.match(guide({...base,locked:true}).text,/伏せ中/);
assert.match(guide({...base,cost:7}).text,/マナが3不足/);
assert.equal(guide({...base,cost:7}).modeDisabled,false,'Summon shortage must not block a possible evolution using difference mana');
assert.match(guide({...base,summonFull:true}).text,/上限/);
assert.match(guide({...base,summonSpace:false}).text,/空きマスがありません/);
assert.match(guide({...base,mode:'evolve'}).text,/光る味方/);
assert.match(guide({...base,mode:'evolve',evolveReady:true}).text,/進化を実行.*確定/);
assert.equal(guide({...base,mode:'evolve',evolveCandidates:false}).modeDisabled,true);
assert.equal(guide({...base,mode:'attack'}).boardVisible,false,'Hand guidance must not override attack instructions');
const sup={...base,support:true,mode:'support',supportNeed:'unit',supportTarget:'ally'};
assert.match(guide(sup).text,/味方をタップ/);
assert.match(guide({...sup,supportTarget:'enemy'}).text,/敵をタップ/);
assert.match(guide({...sup,supportNeed:'unit2',supportFirst:false}).text,/1体目/);
assert.match(guide({...sup,supportNeed:'unit2',supportFirst:true}).text,/2体目/);
assert.match(guide({...sup,supportNeed:'unitCell',supportFirst:true}).text,/空きマス/);
assert.match(guide({...sup,supportNeed:'units',supportCount:3,supportPicked:1}).text,/3体.*1体選択済み/);
assert.match(guide({...sup,supportNeed:'none',supportReady:true}).text,/対象選択は不要.*確定/);
assert.match(guide({...sup,supportReady:true}).text,/選択済み.*確定/);
assert.match(guide({...sup,supportNeed:'search'}).text,/カード選択/);
assert.equal(guide({...sup,cost:9}).modeDisabled,true);
console.log('PASS: next steps for summon/evolution/support, all target stages, mana/turn/locked/full blockers, and no stale attack guidance');
